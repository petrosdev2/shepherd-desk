#!/bin/bash
# One source of truth: src/*.js + src/app.css build BOTH the single-file
# prototype (shepherd-desk.html) and the Next.js app (web/).
set -e
cd "$(dirname "$0")"
mkdir -p build web/lib web/app

# ---- shared script bundle
cat src/core.js src/views1.js src/views2.js src/actions.js > build/app.js
node --check build/app.js

# ---- 1. single-file prototype (Claude artifact / static hosting)
{
echo '<title>Shepherd Desk</title>'
echo '<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>'
echo '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,600;12..96,700&family=Public+Sans:wght@400;500;600;700&display=swap">'
echo '<style>'; cat src/app.css; echo '</style>'
echo '<div id="app"></div><div id="modal-root" hidden></div><div id="toasts" aria-live="polite"></div>'
echo '<script>'; cat build/app.js; echo '</script>'
} > shepherd-desk.html

# ---- 2. Next.js app: same code as an ES module + the same stylesheet
{
echo '/* AUTO-GENERATED by build.sh from ../../src — edit the files in src/ instead. */'
echo '/* eslint-disable */'
echo 'export function startApp(STORE) {'
cat build/app.js
echo '}'
} > web/lib/app.generated.js
{
echo '/* AUTO-GENERATED by build.sh from ../../src/app.css — edit src/app.css instead. */'
cat src/app.css
} > web/app/app.css
node --check web/lib/app.generated.js
echo "built: $(wc -c < shepherd-desk.html) bytes html, $(wc -c < web/lib/app.generated.js) bytes module"
